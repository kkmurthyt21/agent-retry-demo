CREATE TABLE IF NOT EXISTS workflows (
 workflow_id VARCHAR(160) PRIMARY KEY, tenant VARCHAR(80) NOT NULL,
 subject_name VARCHAR(80) NOT NULL, role_name VARCHAR(80) NOT NULL,
 status VARCHAR(24) NOT NULL, state_version INT NOT NULL,
 approved_json CLOB NOT NULL, plan_json CLOB,
 deadline_ms BIGINT NOT NULL, planner_runs INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS action_intents (
 action_key VARCHAR(255) PRIMARY KEY, workflow_id VARCHAR(160) NOT NULL REFERENCES workflows(workflow_id),
 tenant VARCHAR(80) NOT NULL, fingerprint VARCHAR(64) NOT NULL,
 status VARCHAR(24) NOT NULL, receipt_json CLOB
);
CREATE TABLE IF NOT EXISTS event_queue (
 delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workflow_id VARCHAR(160) NOT NULL REFERENCES workflows(workflow_id),
 consumer VARCHAR(32) NOT NULL, source VARCHAR(32) NOT NULL, event_id VARCHAR(200) NOT NULL,
 event_json CLOB NOT NULL, status VARCHAR(24) NOT NULL, next_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS processed_events (
 consumer VARCHAR(32) NOT NULL, source VARCHAR(32) NOT NULL, event_id VARCHAR(200) NOT NULL,
 fingerprint VARCHAR(64) NOT NULL, status VARCHAR(24) NOT NULL, outcome VARCHAR(80),
 PRIMARY KEY(consumer, source, event_id)
);
CREATE TABLE IF NOT EXISTS stage_budgets (
 workflow_id VARCHAR(160) NOT NULL REFERENCES workflows(workflow_id), stage VARCHAR(32) NOT NULL,
 delivery_attempts INT NOT NULL DEFAULT 0, processing_attempts INT NOT NULL DEFAULT 0,
 next_at BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(workflow_id, stage)
);
CREATE TABLE IF NOT EXISTS policy_decisions (
 decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workflow_id VARCHAR(160) NOT NULL, checkpoint VARCHAR(40) NOT NULL,
 subject_name VARCHAR(80) NOT NULL, policy_version VARCHAR(16) NOT NULL,
 decision VARCHAR(16) NOT NULL, reason VARCHAR(1000) NOT NULL, recorded_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS failures (
 failure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workflow_id VARCHAR(160), event_id VARCHAR(200), stage VARCHAR(32) NOT NULL,
 category VARCHAR(24) NOT NULL, reason VARCHAR(4000) NOT NULL,
 disposition VARCHAR(32) NOT NULL, attempt_number INT NOT NULL, recorded_at BIGINT NOT NULL
);
